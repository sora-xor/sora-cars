  assert.equal(await p.locator('[data-garage="refresh"]').isDisabled(), true);
  assert.match(await p.locator('.shop-feature h2').innerText(), /はじまりの朝焼け/);
  assert.equal(await p.locator('.shop-feature h2 small[lang="en"]').innerText(), 'FIRST LIGHT');
  await p.screenshot({ path: 'output/browser/shop/desktop.png', fullPage: true });
  await p.setViewportSize({ width: 390, height: 844 });
  await p.locator('[data-garage="select:club-aero-86"]').click();
  assert.match(await p.locator('.shop-feature h2').innerText(), /クラブ・エアロ86/);
  await p.locator('.club-shop').evaluate(e => e.parentElement.scrollTo(0, 0));
  await p.screenshot({ path: 'output/browser/shop/mobile.png', fullPage: true });
  assert.equal(await p.evaluate(() => document.documentElement.scrollWidth > innerWidth), false);
  // Production main.ts: story context is a hash route, not inventory authority.
  await p.goto(`${origin}/#/story`);
  await p.locator('[data-action="story-workshop-0"]').click();
  await p.waitForURL('**/#/shop/story/0');
  assert.match(await p.locator('.workshop-speaker').innerText(), /空本/);
  assert.equal(await p.locator('[data-garage="refresh"]').isDisabled(), true);
  assert.deepEqual(await p.evaluate(() => JSON.parse(window.render_game_to_text()).garage.owned), []);
  await p.reload();
  await p.waitForSelector('.shop-story-context');
  assert.equal(await p.evaluate(() => JSON.parse(window.render_game_to_text()).garage.storyChapter), 0);
  await p.screenshot({ path: 'output/browser/shop/story-mobile.png', fullPage: true });
  assert.equal(await p.evaluate(() => document.documentElement.scrollWidth > innerWidth), false);
  await p.locator('[data-garage="collection"]').click();
  const designTop = await p.locator('.shop-feature').evaluate(e => e.getBoundingClientRect().top);
  assert.ok(designTop > 0 && designTop < 250, 'Story workshop scrolls to the actual item designs');
  await p.screenshot({ path: 'output/browser/shop/story-design-mobile.png', fullPage: true });
  await p.locator('.workshop-actions [data-action="chapter-0"]').click();
  await p.waitForSelector('.cutscene');
  await p.locator('[data-action="scene-skip"]').click();
  await p.waitForFunction(() => JSON.parse(window.render_game_to_text()).mode === 'race');
  assert.equal(await p.evaluate(() => JSON.parse(window.render_game_to_text()).story.activeChapter), 0);
  // Explicit local chapter-access fixture for all twelve workshop conversations.
  await p.evaluate(() => localStorage.setItem('sora-cars:story:sky-1986', '12'));
  const expected = ['aki-first-light', 'daichi-harbor-line', 'mei-sakura-film', 'ren-radio-night', 'yui-solar-grid', 'club-aero-86', 'club-neon-pulse', 'ren-radio-night', 'yui-solar-grid', 'mei-sakura-film', 'club-aero-86', 'jun-transistor'];
