import { readFile, writeFile, mkdir, realpath, stat } from 'node:fs/promises';
import { resolve } from 'node:path';
import { pathToFileURL } from 'node:url';
import { loadStreetGeneration, streetArtifactHash as hash } from './lib/street-generation';
import { STREET_ROUTE_IDS, streetRoutePackage } from './lib/street-routes';

interface Descriptor {
  id: string; japanese: string; name: string; bundlePath: string; bundleSha256: string; bundleBytes: number;
  musicPath: string; musicSha256: string; musicBytes: number; musicDurationSeconds: number;
}
const MANIFEST = 'src/game/street/asset-manifest.ts';
/** The packaged routes already listed in this checkout's generated manifest. */
async function currentManifest(root: string): Promise<Descriptor[]> {
  let text: string;
  try { text = await readFile(resolve(root, MANIFEST), 'utf8'); } catch { return []; }
  const json = /export const STREET_ASSET_MANIFEST = (\[[\s\S]*\]) as const;/.exec(text)?.[1];
  if (!json) throw new Error('The street asset manifest is not in its generated form.');
  return JSON.parse(json) as Descriptor[];
}

/** Package the exact eight-car output selected by each fresh generation manifest,
 * one per route, with that route's authored recording. Routes not packaged now
 * keep their current manifest entries and files. This checks local producer
 * provenance, not proof or ledger qualification. */
export async function packageStreetAssets(projectRoot: string, generationFiles: readonly string[]) {
  const root = await realpath(projectRoot);
  const packaged = new Map<string, Descriptor>();
  for (const generationFile of generationFiles) {
    const generation = await loadStreetGeneration(projectRoot, generationFile);
    const { bytes: bundle, bundle: { track } } = await generation.readBundle(8);
    if (packaged.has(track.id)) throw new Error(`Two generations package ${track.id}.`);
    const names = streetRoutePackage(track.id);
    const musicPath = resolve(root, 'world/audio', track.sound.asset);
    if (await realpath(musicPath) !== musicPath) throw new Error('Music must be a direct file.');
    const musicStat = await stat(musicPath);
    if (!musicStat.isFile() || musicStat.size <= 0 || musicStat.size > 64 * 1024 * 1024) throw new Error('Invalid music size.');
    const music = await readFile(musicPath);
    if (music.length !== musicStat.size) throw new Error('Music changed while reading.');
    if (hash(music) !== track.sound.sha256) throw new Error(`${track.sound.asset} differs from the authored digest.`);
    await generation.verifyUnchanged();
    const descriptor = { id: track.id, japanese: names.japanese, name: names.name,
      bundlePath: `assets/street/${names.stem}-${hash(bundle)}.json`, bundleSha256: hash(bundle), bundleBytes: bundle.length,
      musicPath: `assets/street/${names.musicStem}-${hash(music)}.m4a`, musicSha256: hash(music), musicBytes: music.length,
      musicDurationSeconds: track.sound.durationMs / 1000 };
    await mkdir(resolve(root, 'public/assets/street'), { recursive: true });
    await writeFile(resolve(root, 'public', descriptor.bundlePath), bundle);
    await writeFile(resolve(root, 'public', descriptor.musicPath), music);
    packaged.set(track.id, descriptor);
  }
  const current = new Map((await currentManifest(root)).map(item => [item.id, item]));
  const manifest = STREET_ROUTE_IDS.flatMap(id => packaged.get(id) ?? current.get(id) ?? []);
  await writeFile(resolve(root, MANIFEST), `// Generated by scripts/package-street-assets.ts; exact native producer inventory checked.\nexport const STREET_ASSET_MANIFEST = ${JSON.stringify(manifest, null, 2)} as const;\n`);
  return [...packaged.values()];
}

if (process.argv[1] && import.meta.url === pathToFileURL(resolve(process.argv[1])).href) {
  const args = process.argv.slice(2);
  if (!args.length || args.length % 2 || args.some((value, i) => i % 2 === 0 ? value !== '--generation' : !value)) {
    throw new Error('Use --generation output/<fresh-generation>/generation.json, once per route.');
  }
  console.log(JSON.stringify(await packageStreetAssets(process.cwd(), args.filter((_, i) => i % 2)), null, 2));
}
