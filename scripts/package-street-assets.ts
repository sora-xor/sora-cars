import { readFile, writeFile, mkdir, realpath, stat } from 'node:fs/promises';
import { resolve } from 'node:path';
import { pathToFileURL } from 'node:url';
import { loadStreetGeneration, streetGenerationArgument, streetArtifactHash as hash } from './lib/street-generation';

/** Package the exact eight-car output selected by a fresh generation manifest.
 * This checks local producer provenance, not proof or ledger qualification. */
export async function packageStreetAssets(projectRoot: string, generationFile: string) {
  const generation = await loadStreetGeneration(projectRoot, generationFile);
  const root = await realpath(projectRoot);
  const { bytes: bundle } = await generation.readBundle(8);
  const musicPath = resolve(root, 'world/audio/yasukuni-1986.m4a');
  if (await realpath(musicPath) !== musicPath) throw new Error('Music must be a direct file.');
  const musicStat = await stat(musicPath);
  if (!musicStat.isFile() || musicStat.size <= 0 || musicStat.size > 64 * 1024 * 1024) throw new Error('Invalid music size.');
  const music = await readFile(musicPath);
  if (music.length !== musicStat.size) throw new Error('Music changed while reading.');
  await generation.verifyUnchanged();
  const descriptor = { id: 'tokyo-1986', japanese: '東京・暁の街道', name: 'Tokyo · Road to Dawn',
    bundlePath: `assets/street/tokyo-${hash(bundle)}.json`, bundleSha256: hash(bundle), bundleBytes: bundle.length,
    musicPath: `assets/street/yasukuni-${hash(music)}.m4a`, musicSha256: hash(music), musicBytes: music.length,
    musicDurationSeconds: 254.952 };
  await mkdir(resolve(root, 'public/assets/street'), { recursive: true });
  await writeFile(resolve(root, 'public', descriptor.bundlePath), bundle);
  await writeFile(resolve(root, 'public', descriptor.musicPath), music);
  await writeFile(resolve(root, 'src/game/street/asset-manifest.ts'), `// Generated by scripts/package-street-assets.ts; exact native producer inventory checked.\nexport const STREET_ASSET_MANIFEST = ${JSON.stringify([descriptor], null, 2)} as const;\n`);
  return descriptor;
}

if (process.argv[1] && import.meta.url === pathToFileURL(resolve(process.argv[1])).href) {
  console.log(JSON.stringify(await packageStreetAssets(process.cwd(), streetGenerationArgument(process.argv.slice(2))), null, 2));
}
