import { createHash } from 'node:crypto';
import { realpath } from 'node:fs/promises';
import { readBoundedNativeFile } from './native-file-io.mjs';
import { isAbsolute, resolve } from 'node:path';

export const STREET_LAYOUT_SOURCE = 'crates/iroha_data_model/src/street_v1/layout.rs';
export const STREET_LAYOUT_COPY = 'world/native/generated/street_layout_v1.rs';
export const STREET_LAYOUT_METADATA = 'world/native/generated/street_layout_v1.provenance.json';
export const STREET_LAYOUT_BROWSER = 'src/game/street/generated/layout-v1.ts';
const ROOT = resolve(import.meta.dirname, '../..');
const sha256 = bytes => createHash('sha256').update(bytes).digest('hex');

const boundedFile = path => readBoundedNativeFile(path, 1_048_576);

// These are metadata arrays, not a Rust evaluator. Any nonliteral declaration
// requires an explicit generator change and new provenance.
function stringArray(source, name, count) {
  const pattern = new RegExp(`pub const ${name}\\s*:\\s*\\[&str;\\s*${count}\\s*\\]\\s*=\\s*\\[([^\\]]*)\\];`, 'g');
  const matches = [...source.matchAll(pattern)];
  if (matches.length !== 1) throw new Error(`Expected one literal native ${name} array.`);
  const body = matches[0][1];
  const parts = body.trim().replace(/,\s*$/, '').split(',').map(value => value.trim());
  if (parts.length !== count || parts.some(value => !/^"[A-Za-z][A-Za-z0-9]*"$/.test(value))) {
    throw new Error(`Unsupported native ${name} metadata syntax.`);
  }
  const values = parts.map(value => JSON.parse(value));
  if (new Set(values).size !== count) throw new Error(`Duplicate native ${name} metadata.`);
  return values;
}

export function streetLayoutArtifacts(bytes) {
  const sourceSha256 = sha256(bytes);
  const source = new TextDecoder('utf-8', { fatal: true }).decode(bytes);
  const cars = stringArray(source, 'CAR_FIELDS', 11);
  const headers = stringArray(source, 'STATE_HEADER_FIELDS', 3);
  const browser = Buffer.from([
    '// Generated by scripts/generate-street-layout.mjs. Do not edit.',
    `// Native source: ${STREET_LAYOUT_SOURCE}; SHA-256 ${sourceSha256}.`,
    '// Schema metadata only; local Street practice remains motion-only.',
    `export const STREET_CAR_FIELDS = Object.freeze(${JSON.stringify(cars)} as const);`,
    `export const STREET_STATE_HEADER_FIELDS = Object.freeze(${JSON.stringify(headers)} as const);`,
    '',
  ].join('\n'));
  const metadata = {
    schema: 'sora-cars.native-street-layout-copy.v1',
    source: { key: STREET_LAYOUT_SOURCE, sha256: sourceSha256, bytes: bytes.length },
    rust: { path: STREET_LAYOUT_COPY, sha256: sourceSha256, bytes: bytes.length },
    browser: { path: STREET_LAYOUT_BROWSER, sha256: sha256(browser), bytes: browser.length },
    scope: 'Shared layout metadata; no profile registration, proof admission or removal authority.',
  };
  return { browser, metadata, metadataBytes: Buffer.from(JSON.stringify(metadata, null, 2) + '\n') };
}

export async function readNativeStreetLayout(irohaRoot) {
  if (typeof irohaRoot !== 'string' || !isAbsolute(irohaRoot)) {
    throw new Error('Select the native source explicitly with --iroha-root or SORA_CARS_IROHA_ROOT (absolute path).');
  }
  const root = await realpath(irohaRoot);
  const path = resolve(root, STREET_LAYOUT_SOURCE);
  if (await realpath(path) !== path) throw new Error('The selected native layout must be a direct source file.');
  return { root, path, bytes: await boundedFile(path) };
}

/** Require the selected native source, byte-exact Rust copy, and generated
 * browser schema to agree. Physical checkout paths never enter the schema. */
export async function verifyStreetLayout(irohaRoot = process.env.SORA_CARS_IROHA_ROOT) {
  const native = await readNativeStreetLayout(irohaRoot);
  const expected = streetLayoutArtifacts(native.bytes);
  const pairs = [
    [STREET_LAYOUT_COPY, native.bytes],
    [STREET_LAYOUT_BROWSER, expected.browser],
    [STREET_LAYOUT_METADATA, expected.metadataBytes],
  ];
  for (const [name, wanted] of pairs) {
    const actual = await boundedFile(resolve(ROOT, name));
    if (!actual.equals(wanted)) throw new Error(`Stale generated Street layout: ${name}; regenerate from the selected native source.`);
  }
  if (!(await boundedFile(native.path)).equals(native.bytes)) throw new Error('Native Street layout changed during verification.');
  return { ...native, ...expected };
}
